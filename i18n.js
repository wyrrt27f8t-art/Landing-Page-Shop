function gewuenschteSprache() {
  const ausAdresse = new URLSearchParams(location.search).get("lang");
  if (SPRACHEN.includes(ausAdresse)) return ausAdresse;

  try {
    const gemerkt = localStorage.getItem("mafo-sprache");
    if (SPRACHEN.includes(gemerkt)) return gemerkt;
  } catch (e) {
    /* Privater Modus: kein Speicher, kein Problem. */
  }

  for (const bevorzugt of navigator.languages || [navigator.language || ""]) {
    const kurz = bevorzugt.slice(0, 2).toLowerCase();
    if (SPRACHEN.includes(kurz)) return kurz;
  }
  return STANDARD;
}

function setzeSprache(sprache) {
  const woerter = TEXTE[sprache] || TEXTE[STANDARD];

  document.documentElement.lang = sprache;

  // Ganze Textblöcke je Sprache (Rechtsseiten): Die Fassungen liegen in
  // <template data-sprache="…">. Gezeigt wird immer nur eine, damit Sprungmarken
  // wie #paket eindeutig bleiben.
  document.querySelectorAll("[data-sprachinhalt]").forEach((ziel) => {
    const vorlage =
      document.querySelector(`template[data-sprache="${sprache}"][data-fuer="${ziel.id}"]`) ||
      document.querySelector(`template[data-sprache="de"][data-fuer="${ziel.id}"]`);
    if (!vorlage || ziel.dataset.gezeigt === vorlage.dataset.sprache) return;
    ziel.replaceChildren(vorlage.content.cloneNode(true));
    ziel.dataset.gezeigt = vorlage.dataset.sprache;
    // Sprungmarke aus der Adresse nach dem Wechsel wieder anfahren
    if (location.hash) {
      const anker = document.getElementById(decodeURIComponent(location.hash.slice(1)));
      if (anker && ziel.contains(anker)) anker.scrollIntoView();
    }
  });

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const text = woerter[el.dataset.i18n];
    if (text !== undefined) el.textContent = text;
  });

  // Beschriftungen für Bildschirmleser, zum Beispiel an Knöpfen mit Symbol
  document.querySelectorAll("[data-i18n-label]").forEach((el) => {
    const text = woerter[el.dataset.i18nLabel];
    if (text !== undefined) el.setAttribute("aria-label", text);
  });

  // Platzhalter in Eingabefeldern
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const text = woerter[el.dataset.i18nPlaceholder];
    if (text !== undefined) el.placeholder = text;
  });

  // Bildbeschreibungen
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const text = woerter[el.dataset.i18nAlt];
    if (text !== undefined) el.alt = text;
  });

  // Titel und Beschreibung, sofern die Seite eigene hinterlegt hat
  const kopf = document.querySelector('[data-i18n-title]');
  if (kopf) {
    const schluessel = kopf.dataset.i18nTitle;
    if (woerter[schluessel]) document.title = woerter[schluessel];
  }

  document.querySelectorAll(".lang-switch button").forEach((b) => {
    b.setAttribute("aria-current", b.dataset.lang === sprache ? "true" : "false");
  });

  try {
    localStorage.setItem("mafo-sprache", sprache);
  } catch (e) {
    /* siehe oben */
  }
}

document.addEventListener("DOMContentLoaded", () => {
  setzeSprache(gewuenschteSprache());

  document.querySelectorAll(".lang-switch button").forEach((b) => {
    b.addEventListener("click", () => setzeSprache(b.dataset.lang));
  });
});

